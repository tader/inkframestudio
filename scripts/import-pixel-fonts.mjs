import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const rootDir = path.resolve(__dirname, "..");

const SOURCES = {
  "px-sans": {
    regular: path.join(rootDir, "third_party/pixel-fonts/PX Sans/PXSansRegular.ttf"),
    bold: path.join(rootDir, "third_party/pixel-fonts/PX Sans/PXSansBold.ttf")
  },
  "px-mono-special": {
    regular: path.join(rootDir, "third_party/pixel-fonts/PX Mono Special/PX Mono Special Regular.ttf")
  }
};

async function main() {
  const encoded = {};
  for (const [family, weights] of Object.entries(SOURCES)) {
    encoded[family] = {};
    for (const [weight, filePath] of Object.entries(weights)) {
      const bytes = await readFile(filePath);
      encoded[family][weight] = bytes.toString("base64");
    }
  }

  const output = `// Generated by scripts/import-pixel-fonts.mjs
export const FONT_BINARY_BASE64 = ${JSON.stringify(encoded, null, 2)} as const;
`;

  const outPath = path.join(rootDir, "packages/render-core/src/generated-font-data.ts");
  await mkdir(path.dirname(outPath), { recursive: true });
  await writeFile(outPath, output, "utf8");
}

await main();

import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const rootDir = path.resolve(__dirname, "..");

const metadataPath = path.join(rootDir, "node_modules/@fortawesome/fontawesome-free/metadata/icon-families.json");

const FONT_SOURCES = {
  "fa-solid": path.join(rootDir, "node_modules/@fortawesome/fontawesome-free/webfonts/fa-solid-900.woff2"),
  "fa-regular": path.join(rootDir, "node_modules/@fortawesome/fontawesome-free/webfonts/fa-regular-400.woff2"),
  "fa-brands": path.join(rootDir, "node_modules/@fortawesome/fontawesome-free/webfonts/fa-brands-400.woff2")
};

const FONT_ROLE_BY_STYLE = {
  solid: "fa-solid",
  regular: "fa-regular",
  brands: "fa-brands"
};

const PACK_LABEL_BY_STYLE = {
  solid: "solid",
  regular: "regular",
  brands: "brands"
};

async function buildFontData() {
  const encoded = {};
  for (const [family, sourcePath] of Object.entries(FONT_SOURCES)) {
    const bytes = await readFile(sourcePath);
    encoded[family] = { regular: bytes.toString("base64") };
  }
  return encoded;
}

async function buildIconCatalog() {
  const metadata = JSON.parse(await readFile(metadataPath, "utf8"));
  const definitions = [];
  const glyphMap = {};

  for (const [slug, entry] of Object.entries(metadata)) {
    const freeStyles = entry?.familyStylesByLicense?.free ?? [];
    for (const familyStyle of freeStyles) {
      const style = familyStyle?.style;
      const fontFamily = FONT_ROLE_BY_STYLE[style];
      const pack = PACK_LABEL_BY_STYLE[style];
      if (!fontFamily || !pack) {
        continue;
      }
      const id = `${fontFamily}:${slug}`;
      const keywords = Array.from(new Set([entry.label, ...(entry.search?.terms ?? [])]))
        .filter((value) => typeof value === "string" && value.trim().length > 0)
        .map((value) => String(value));
      const definition = {
        id,
        label: String(entry.label ?? slug),
        pack,
        keywords
      };
      const glyph = {
        ...definition,
        fontFamily,
        unicode: String(entry.unicode ?? ""),
        char: String.fromCodePoint(parseInt(String(entry.unicode), 16))
      };
      definitions.push(definition);
      glyphMap[id] = glyph;
    }
  }

  definitions.sort((left, right) =>
    left.pack.localeCompare(right.pack) ||
    left.label.localeCompare(right.label) ||
    left.id.localeCompare(right.id)
  );

  const sortedGlyphMap = Object.fromEntries(Object.entries(glyphMap).sort(([left], [right]) => left.localeCompare(right)));
  return { definitions, glyphMap: sortedGlyphMap };
}

async function main() {
  const [fontData, { definitions, glyphMap }] = await Promise.all([
    buildFontData(),
    buildIconCatalog()
  ]);

  const fontDataOutput = `// Generated by scripts/generate-font-awesome.mjs
export const FONT_AWESOME_FONT_BINARY_BASE64 = ${JSON.stringify(fontData, null, 2)} as const;
`;

  const iconOutput = `// Generated by scripts/generate-font-awesome.mjs
import type { FontFamily, IconDefinition } from "./types.js";

export interface FontAwesomeIconGlyphDefinition extends IconDefinition {
  pack: "solid" | "regular" | "brands";
  keywords: string[];
  fontFamily: FontFamily;
  unicode: string;
  char: string;
}

export const FONT_AWESOME_ICON_DEFINITIONS: IconDefinition[] = ${JSON.stringify(definitions, null, 2)} as const;

export const FONT_AWESOME_ICON_GLYPHS: Record<string, FontAwesomeIconGlyphDefinition> = ${JSON.stringify(glyphMap, null, 2)} as const;
`;

  const fontOutPath = path.join(rootDir, "packages/render-core/src/generated-font-awesome-data.ts");
  const iconOutPath = path.join(rootDir, "packages/render-core/src/generated-font-awesome-icons.ts");
  const iconJsonOutPath = path.join(rootDir, "rust/backend-api/assets/font-awesome-icons.json");
  await mkdir(path.dirname(fontOutPath), { recursive: true });
  await mkdir(path.dirname(iconJsonOutPath), { recursive: true });
  await writeFile(fontOutPath, fontDataOutput, "utf8");
  await writeFile(iconOutPath, iconOutput, "utf8");
  await writeFile(iconJsonOutPath, JSON.stringify(definitions, null, 2), "utf8");
}

await main();
